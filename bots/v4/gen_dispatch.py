"""Generate a two-bot dispatcher tree (src/a, src/b) as in bots/v2, from two plain bot source trees.

v3a = v2's dispatcher (bots/v2/src/main.cpp, route.h: pilgrimage -> B) with A = bots/v3a/srcA (v2a + w7 part 1 + w9
contest siege + w8 build C on monolith) and B = b-v418d (as shipped in bots/v2/src/b). Same transform as
bots/v2/gen_dispatch.py: each .cpp gets the bot's system includes hoisted to global scope, then its whole body wrapped in
`namespace va {` / `namespace vb {`; headers are copied unchanged; main.cpp is dropped; entry.cpp is added; A's own
salt burn in plan.cpp is disabled (the dispatcher's main.cpp burns it).

Run: py -I bots/v3a/gen_dispatch.py [--a SRC] [--b SRC] [--out DIR]
Defaults: --a bots/v3a/srcA, --b bots/b-v418d/src, --out bots/v3a/src.
"""
import argparse, os, re, shutil

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SYS = re.compile(r'^\s*#\s*include\s*<[^>]+>')
ENTRY = """// Dispatcher entry points for this bot copy (generated by gen_dispatch.py).
#include "bot.h"
#include "draft.h"
static Bot* g_dispatch_bot = nullptr;
void dispatch_init() { g_dispatch_bot = new Bot(); }
void dispatch_draft() { play_draft(); }
void dispatch_turn() { g_dispatch_bot->play_turn(); }
"""

ap = argparse.ArgumentParser()
ap.add_argument("--a", default=os.path.join(ROOT, "bots", "v3a", "srcA"))
ap.add_argument("--b", default=os.path.join(ROOT, "bots", "b-v418d", "src"))
ap.add_argument("--out", default=os.path.join(ROOT, "bots", "v3a", "src"))
args = ap.parse_args()
SRCS = {"a": ("va", args.a), "b": ("vb", args.b)}

for sub, (ns, src) in SRCS.items():
    dst = os.path.join(args.out, sub)
    if os.path.isdir(dst): shutil.rmtree(dst)
    os.makedirs(dst)
    files = {f: open(os.path.join(src, f), encoding="utf-8").read() for f in os.listdir(src)
             if f.endswith((".cpp", ".h")) and f != "main.cpp" and f != "salt.h"}
    sysinc = sorted({l.strip() for t in files.values() for l in t.splitlines() if SYS.match(l)})
    if "#include <cambc.h>" not in sysinc: sysinc.append("#include <cambc.h>")
    if "#include <iostream>" not in sysinc: sysinc.append("#include <iostream>")
    if sub == "a":   # the dispatcher burns the salt for both bots; A's own burn is disabled
        t = files["plan.cpp"]
        t2 = t.replace('#if __has_include("salt.h")', '#if 0   // w3: salt burn moved to the dispatcher (src/main.cpp)')
        assert t2 != t, "plan.cpp salt guard not found"
        files["plan.cpp"] = t2
    files["entry.cpp"] = ENTRY
    for f, t in files.items():
        out = t
        if f.endswith(".cpp"):
            out = ("// w3 dispatcher copy: system headers at global scope, bot code in namespace " + ns + "\n"
                   + "\n".join(sysinc) + "\nnamespace " + ns + " {\n" + t + ("" if t.endswith("\n") else "\n")
                   + "} // namespace " + ns + "\n")
        open(os.path.join(dst, f), "w", encoding="utf-8", newline="\n").write(out)
    print(sub, ns, len(files), "files;", len(sysinc), "system includes hoisted")
