"""Generate bots/w3/src/{a,b}/ from bots/v1/src (A) and bots/b-v418d/src (B).

Each .cpp gets every system include the bot uses hoisted to the top (global scope), then its
whole body (local includes too) wrapped in `namespace va {` / `namespace vb {`. Headers are copied
unchanged: they are only ever included inside the namespace, and their system includes are
already satisfied (include guards / #pragma once). main.cpp is dropped; entry.cpp is added.
Run: py -I bots/w3/gen_dispatch.py
"""
import os, re, shutil
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
W3 = os.path.join(ROOT, "bots", "v2", "src")
SRCS = {"a": ("va", os.path.join(ROOT, "bots", "v2a", "src")),
        "b": ("vb", os.path.join(ROOT, "bots", "b-v418d", "src"))}
SYS = re.compile(r'^\s*#\s*include\s*<[^>]+>')
ENTRY = """// Dispatcher entry points for this bot copy (generated by gen_dispatch.py).
#include "bot.h"
#include "draft.h"
static Bot* g_dispatch_bot = nullptr;
void dispatch_init() { g_dispatch_bot = new Bot(); }
void dispatch_draft() { play_draft(); }
void dispatch_turn() { g_dispatch_bot->play_turn(); }
"""
for sub, (ns, src) in SRCS.items():
    dst = os.path.join(W3, sub)
    if os.path.isdir(dst): shutil.rmtree(dst)
    os.makedirs(dst)
    files = {f: open(os.path.join(src, f), encoding="utf-8").read() for f in os.listdir(src)
             if f.endswith((".cpp", ".h")) and f != "main.cpp" and f != "salt.h"}
    sysinc = sorted({l.strip() for t in files.values() for l in t.splitlines() if SYS.match(l)})
    if "#include <cambc.h>" not in sysinc: sysinc.append("#include <cambc.h>")
    if "#include <iostream>" not in sysinc: sysinc.append("#include <iostream>")
    if sub == "a":   # the dispatcher burns the salt for both bots; A's own burn is disabled
        t = files["plan.cpp"]
        t2 = t.replace('#if __has_include("salt.h")', '#if 0   // w3: salt burn moved to the dispatcher (src/main.cpp)')
        assert t2 != t, "plan.cpp salt guard not found"
        files["plan.cpp"] = t2
    files["entry.cpp"] = ENTRY
    for f, t in files.items():
        out = t
        if f.endswith(".cpp"):
            out = ("// w3 dispatcher copy: system headers at global scope, bot code in namespace " + ns + "\n"
                   + "\n".join(sysinc) + "\nnamespace " + ns + " {\n" + t + ("" if t.endswith("\n") else "\n")
                   + "} // namespace " + ns + "\n")
        open(os.path.join(dst, f), "w", encoding="utf-8", newline="\n").write(out)
    print(sub, ns, len(files), "files;", len(sysinc), "system includes hoisted")
