"""Build notes/econsim.md from results/econsim.json (+ econsim-sens.json). Re-runs each map's best config to extract routes."""
import sys, json, os
sys.path.insert(0, os.path.dirname(__file__))
from mapmodel import *
from sim import *
from run_all import splits

R = json.load(open(os.path.join(ROOT, 'results', 'econsim.json')))
SENS = json.load(open(os.path.join(ROOT, 'results', 'econsim-sens.json'))) if os.path.exists(os.path.join(ROOT, 'results', 'econsim-sens.json')) else {}
D = load_all()
f = lambda x: f'{x:.2f}'
L = ['# econsim: S2 economy simulator results (engine-1.0 camp values, no enemies)', '',
     'Generated by `tools/econsim/report.py` from `results/econsim.json`, `results/econsim-sens.json`. Code: `tools/econsim/{mapmodel,sim,run_all,sens,report,calibrate}.py`. Run: `python tools/econsim/run_all.py [maps]`, `python tools/econsim/sens.py`, `python tools/econsim/report.py`. Single process, about 6 min.', '',
     '## Model and assumptions', '',
     '- Grid: walls and holes block walking (king moves, 8 directions); BFS from group anchors (the camp nearest the group centroid), altars, spawn A. Spawn B = mirror of A. Our altars = those no farther from A than from B. Camp values from `data/maps21.json` group info (gems, gold, respawn; engine 1.0, kept as data, `gem_scale` swaps them).',
     '- Horizon 900 rounds from round 0; metric = gems tributed per round (bags left at the end are lost). No enemy: contested groups are free (scenario `all`); scenario `half` keeps only groups at least as near to A as to B.',
     '- Team = squads of k champions that move, clear and capture together. Clear time = camp HP (+ span overhead) / (k x dpr), dpr = 50 per champion per round. Feasibility: a squad of k may start a group only if monster strength x clear rounds / k <= 700 (damage per champion); this is what bars wolves/elks from solo play and excludes monoliths (20,000 HP, strength 200). Monsters are not simulated otherwise.',
     '- Capture: 1 round to step on the tile + 5 rounds, reward split evenly among champions present (lowest ID takes the remainder), group respawn = group respawn value after the reward. A group left alone for 2 rounds heals fully (rule doc); the contest notes suggest monoliths keep damage, not modelled.',
     '- Tribute: when any member bag >= bank b (per champion), walk to the nearest own altar, channel ceil(max bag / 10) rounds; optional recall = 5 ticks to spawn then walk to altar.',
     '- Policies: greedy = one blob, nearest alive group, no value; team = one blob, value per round; value = squads (split swept), gems / (wait + travel + clear + capture + amortised tribute trip), exclusive claims; conveyor = blob that leaves one capturer (smallest bag) at each group when the rest can still take the next-best group, capturers farm on their own; orient = beam search (width 6, depth 3) over the next 3 groups with respawn windows. Best bank over {10,20,30,40,60,80} per row.', '']
names = list(D)
summ = []
for nm in names:
    if nm not in R: continue
    r = R[nm]; info = r['info']; n = info['champs']
    L += [f'## {nm} ({n} champions, {info["groups"]} groups, {info["altars"]} own altars)', '']
    notes = []
    if info['unreach']: notes.append(f'**unreachable on foot from spawn: {len(info["unreach"])} groups** ({", ".join(info["unreach"][:4])}{"..." if len(info["unreach"])>4 else ""}); with crystals (range 3, 3-round channel, 10 gold each) every one is reachable')
    if info['mono']: notes.append(f'monolith groups present ({len(info["mono"])}): excluded unless a squad can absorb 200 strength; see sensitivity `mono_ok`')
    if notes: L += ['- ' + x for x in notes] + ['']
    res = r['walk']['all']; half = r['walk']['half']
    L += ['| policy / squads | gems/round (all) | bank | travel | clear | capture | tribute | wait | gems/round (half) |', '|---|---|---|---|---|---|---|---|---|']
    byp = {}
    for k, v in res.items():
        p = k.split('/')[0]
        if p not in byp or v['gpr'] > byp[p][1]['gpr']: byp[p] = (k, v)
    for p, (k, v) in sorted(byp.items(), key=lambda kv: -kv[1][1]['gpr']):
        s = v['share']
        L.append(f"| {k} | {f(v['gpr'])} | {v['bank']} | {s['travel']:.0%} | {s['clear']:.0%} | {s['capture']:.0%} | {s['tribute']:.0%} | {s['wait']:.0%} | {f(half[k]['gpr'])} |")
    bk = max(res, key=lambda k: res[k]['gpr']); gk = byp['greedy'][0]
    g0 = res[gk]['gpr']; b0 = res[bk]['gpr']
    gain = (b0 / g0 - 1) if g0 > 0 else None
    L += ['', f"Best: **{bk}**, bank {res[bk]['bank']}, {f(b0)} gems/round; greedy {f(g0)} ({'+%.0f%%' % (100*gain) if gain is not None else 'n/a'}). Best on own half only: {max(half, key=lambda k: half[k]['gpr'])} ({f(max(v['gpr'] for v in half.values()))}).", '']
    if 'crystal' in r:
        cr = r['crystal']['all']; ck = max(cr, key=lambda k: cr[k]['gpr'])
        L += [f"With crystal hops allowed (unlimited, 3 extra rounds per hop): best {ck} {f(cr[ck]['gpr'])} gems/round vs {f(b0)} on foot.", '']
    if nm in SENS:
        sv = SENS[nm]; row = []
        for vn, bb in sv.items():
            top = max(bb.values()); row.append(f"{vn}: {top[1]} b{top[2]} {top[0]:.2f}")
        L += ['Sensitivity (best policy per assumption): ' + '; '.join(row), '']
    # route extraction
    M = MapModel(nm, D[nm]); pol, sp = bk.split('/')
    S = Sim(M, P(policy=pol, split=splits(n)[sp], bank=res[bk]['bank'], scenario='all')); S.run()
    routes = {}
    for t, gid, sqs in S.log:
        for q in sqs: routes.setdefault(q, []).append(gid)
    rl = {q: v[:10] for q, v in routes.items()}
    nbytes = 2 + sum(1 + len(v) for v in rl.values())
    L += [f"First captures per squad (group ids, in order of the map's group list in `data/maps21.json` after mirroring): " + '; '.join(f"s{q}: {v}" for q, v in sorted(rl.items())) + f". Draft-memory cost for these routes: {nbytes} bytes.", '']
    summ.append((nm, n, bk, res[bk]['bank'], b0, g0, gain, byp))
# summary tables
H = ['## Summary', '', '| map | n | best policy/squads | bank | best g/r | greedy g/r | gain |', '|---|---|---|---|---|---|---|']
for nm, n, bk, b, b0, g0, gain, byp in summ:
    H.append(f"| {nm} | {n} | {bk} | {b} | {f(b0)} | {f(g0)} | {'+%.0f%%' % (100*gain) if gain is not None else 'n/a'} |")
i = L.index('## ambush (5 champions' if False else [x for x in L if x.startswith('## ')][1])
L = L[:i] + H + [''] + L[i:]
open(os.path.join(ROOT, 'notes', 'econsim-body.md'), 'w').write('\n'.join(L))
print('wrote notes/econsim-body.md', len(L))
