"""w7 part 2: per-map counter-draft table for our LAST pick, from intel/matches-2026-10-18.csv.

The CSV stores drafts as sorted sets (all 18,490 side-drafts are alphabetical), so pick order is not recoverable.
The table therefore conditions on set membership: at our last pick we know our first k-1 picks R' (the static
list) and see k-1 enemy picks E' (GameRules, Drafting: simultaneous, revealed as they go). For each map,
each candidate last pick c (our final roster F_c = R' + c) and each enemy champion e:
  cell(c, e)  = side-games with our roster == F_c and e in the enemy roster: n and mean rating-adjusted excess
                (win - Elo expectation, 400 scale, pre-group ratings).
  base(c)     = side-games with our roster == F_c, any enemy; mean x shrunk toward the map baseline 0: x * n / (n + K).
  I(c, e)     = (x_cell - x_roster) * n_cell / (n_cell + K): the enemy-conditional shift, shrunk toward 0.
  score(c|E') = base(c) + mean over seen e of I(c, e)   (cells below NMIN contribute 0, i.e. no information).
A cell counts only when n >= NMIN (30) on all data and >= NMIN/2 in each half. Every number is computed on all data and on two halves split by a hash of
group_id (h1, h2), so the bot can demand that an override holds in both halves.
Output: bots/w7/src/counter_table.h.  usage: py -I tools/v3/w7_counter_table.py [--out path]
"""
import sys, zlib, collections
sys.path.insert(0, "C:/cambc-solo/tools/v3")
from w7_drafts import ROWS, S

K, NMIN = 30, 30
ENUM = ["Ryth", "Vesper", "Vendetta", "CassiIssac", "Stellar", "Prism", "Marcella", "Willow", "Ren", "Varg", "Tavi"]
CPP = ["ryth", "vesper_vale", "vendetta", "cassi_and_issac", "stellar", "prism", "marcella", "willow", "ren", "varg", "tavi"]
UNPLAYABLE = {"Willow", "Vesper"}   # heal and dash never cast by our code (kit check, results/w7-draft.md)

# Static lists the bot uses (pick order; mirrors w7_drafts.h draft_p1 / the set the bot is built with).
STATIC = {}
MAPIDS = {  # csv map name -> mapid enum names
    "ambush": ["ambush"], "collision": ["collision_old", "collision_v2"], "contest": ["contest"],
    "corners": ["corners_old", "corners_v2"], "eight": ["eight"], "elkring": ["elkring"],
    "expanse": ["expanse_old", "expanse_v2"], "fragment": ["fragment"], "interlock": ["interlock_old", "interlock_v2"],
    "lanes": ["lanes_old", "lanes_v2"], "monolith": ["monolith"], "packs": ["packs_old", "packs_v2"],
    "pilgrimage": ["pilgrimage"], "rows": ["rows"], "rushbait_v2": ["rushbait"], "stampede": ["stampede"], "swirl": ["swirl"],
}

def load_static(path):
    import json
    return json.load(open(path))

group_of = {}
for r in ROWS: group_of[r["match_id"]] = r["group_id"]
# S rows carry no group id; rebuild with half labels in the same order as w7_drafts.sides (two per CSV row).
half = []
for r in ROWS:
    try: float(r["rating_a"]); float(r["rating_b"])
    except ValueError: continue
    h = zlib.crc32(r["group_id"].encode()) & 1
    half += [h, h]
assert len(half) == len(S)

def stats(L):
    n = len(L)
    return n, (sum(x["win"] - x["exp"] for x in L) / n if n else 0.0)

def build(static):
    out = {}
    for m, lst in static.items():
        g = [(s, h) for s, h in zip(S, half) if s["map"] == m]
        size = len(lst)
        rp = frozenset(lst[:-1]); s_last = lst[-1]
        tabs = {}
        for c in ENUM:
            if c in rp or c in UNPLAYABLE: continue
            F = rp | {c}
            rows = [(s, h) for s, h in g if s["draft"] == F]
            ent = {}
            for tag, sel in (("all", rows), ("h1", [x for x in rows if x[1] == 0]), ("h2", [x for x in rows if x[1] == 1])):
                L = [s for s, _ in sel]
                n, x = stats(L)
                base = x * n / (n + K)
                cells = {}
                for e in ENUM:
                    Le = [s for s in L if e in s["opp"]]
                    ne, xe = stats(Le)
                    cells[e] = (ne, (xe - x) * ne / (ne + K) if ne else 0.0)
                ent[tag] = (n, base, cells)
            tabs[c] = ent
        out[m] = (size, lst, s_last, tabs)
    return out

def emit(tab, path):
    t10 = lambda v: int(round(v * 1000))   # tenths of a percentage point
    L = ["// counter_table.h: GENERATED by tools/v3/w7_counter_table.py from intel/matches-2026-10-18.csv. Do not edit.",
         f"// K={K} (shrinkage, games), NMIN={NMIN} (min games per cell and per base roster). Units: 0.1 pp of",
         "// rating-adjusted excess. One entry per (map, candidate last pick c): base = shrunk excess of our roster R'+c;",
         "// inter[e] = shrunk shift of that excess when the enemy roster held e (0 unless the cell has >= NMIN games).",
         "// all / h1 / h2 = all data and the two halves split by crc32(group_id) & 1. Rule: bots/w7/src/counter.h.",
         "#pragma once", "#include <cstdint>", "#include \"mapid.h\"", "", "namespace ctab {", "",
         "struct Cand { std::int8_t c; std::int16_t base[3]; std::int16_t inter[3][11]; std::uint16_t cell_ok; };   // inter = 0 unless cell_ok bit e",
         "struct MapTab { mapid::MapId id; std::uint8_t size; std::uint16_t rprime; std::int8_t last; const Cand* cands; std::uint8_t ncand; };", ""]
    maps = []
    for m, (size, lst, s_last, tabs) in tab.items():
        rows = []
        for c, ent in tabs.items():
            nb = min(ent[t][0] for t in ("all", "h1", "h2"))
            if ent["all"][0] < NMIN or nb < 5: continue
            ok = 0
            for i, e in enumerate(ENUM):
                if all(ent[t][2][e][0] >= NMIN // 2 for t in ("h1", "h2")) and ent["all"][2][e][0] >= NMIN: ok |= 1 << i
            base = ", ".join(str(t10(ent[t][1])) for t in ("all", "h1", "h2"))
            cells = ", ".join("{" + ", ".join(str(t10(ent[t][2][e][1]) if ok >> i & 1 else 0) for i, e in enumerate(ENUM)) + "}" for t in ("all", "h1", "h2"))
            rows.append(f"    {{{ENUM.index(c)}, {{{base}}}, {{{cells}}}, 0x{ok:x}}},   // {c} n={ent['all'][0]}")
        if not rows: continue
        var = f"k_{m}"
        L.append(f"inline constexpr Cand {var}[] = {{")
        L += rows
        L.append("};")
        rmask = sum(1 << ENUM.index(c) for c in lst[:-1])
        for mid in MAPIDS[m]:
            maps.append(f"    {{mapid::MapId::{mid}, {size}, 0x{rmask:x}, {ENUM.index(s_last)}, {var}, {len(rows)}}},")
    L.append("")
    L.append("inline constexpr MapTab k_maps[] = {")
    L += maps
    L.append("};")
    L += ["", "}  // namespace ctab", ""]
    open(path, "w").write("\n".join(L))

def report(tab):
    for m, (size, lst, s_last, tabs) in tab.items():
        print(f"== {m} static {'+'.join(lst)} last={s_last}")
        for c, ent in sorted(tabs.items(), key=lambda kv: -kv[1]["all"][0]):
            n, base, cells = ent["all"]
            if n < NMIN: continue
            good = [f"{e}:{cells[e][0]}:{cells[e][1]*100:+.1f}" for e in ENUM if cells[e][0] >= NMIN]
            print(f"   {c:<10} n={n:4d} base={base*100:+5.1f}  " + " ".join(good))

MARGIN, INFO = 50, 25   # tenths of a pp: override gap, and the part of it that must come from the enemy's picks

def decide(tabm, eprime):
    """Mirror of counter::pick in bots/w7/src/counter.h. Returns (pick or None, detail)."""
    size, lst, s_last, tabs = tabm
    t10 = lambda v: int(round(v * 1000))
    rows = {}
    for c, ent in tabs.items():
        nb = min(ent[t][0] for t in ("all", "h1", "h2"))
        if ent["all"][0] < NMIN or nb < 5: continue
        ok = [e for e in ENUM if all(ent[t][2][e][0] >= NMIN // 2 for t in ("h1", "h2")) and ent["all"][2][e][0] >= NMIN]
        rows[c] = [(t10(ent[t][1]), {e: t10(ent[t][2][e][1]) if e in ok else 0 for e in ENUM}) for t in ("all", "h1", "h2")]
    if s_last not in rows or not eprime: return None, "static not in table"
    def score(c, t):
        b, inter = rows[c][t]
        return b + sum(inter[e] for e in eprime) / len(eprime)
    best = max(rows, key=lambda c: score(c, 0))
    if best == s_last: return None, "static best"
    gap = [score(best, t) - score(s_last, t) for t in range(3)]
    bgap = rows[best][0][0] - rows[s_last][0][0]
    if gap[0] >= MARGIN and gap[0] - bgap >= INFO and gap[1] > 0 and gap[2] > 0:
        return best, f"gap {gap[0]/10:+.1f} base gap {bgap/10:+.1f} halves {gap[1]/10:+.1f}/{gap[2]/10:+.1f}"
    return None, f"no: best {best} gap {gap[0]/10:+.1f} base {bgap/10:+.1f} halves {gap[1]/10:+.1f}/{gap[2]/10:+.1f}"

def fire_rates(tab):
    for m, tabm in tab.items():
        fires = collections.Counter(); tot = 0
        for sd in S:
            if sd["map"] != m: continue
            opp = sorted(sd["opp"])
            for drop in opp:   # the enemy's unseen last pick is unknown: average over each choice
                ep = [e for e in opp if e != drop]
                c, _ = decide(tabm, ep)
                tot += 1
                if c: fires[c] += 1
        print(f"  fire {m:<12} {sum(fires.values())/max(1,tot)*100:5.1f}% of ladder partial drafts  {dict(fires)}")

if __name__ == "__main__":
    spec = sys.argv[sys.argv.index("--static") + 1] if "--static" in sys.argv else "C:/cambc-solo/tools/v3/w7_static.json"
    out = sys.argv[sys.argv.index("--out") + 1] if "--out" in sys.argv else "C:/cambc-solo/bots/w7/src/counter_table.h"
    tab = build(load_static(spec))
    report(tab)
    fire_rates(tab)
    emit(tab, out)
    print("wrote", out)
